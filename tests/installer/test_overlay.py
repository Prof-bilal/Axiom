"""Every installer overlay source must exist in the ISO build layout.

A missing source raises after archinstall has finished, so the install stops at 88% with no clean error.
Sources are either shipped in iso/phase3/airootfs or generated by scripts/build-phase3-iso.sh.
"""
import os
import sys
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, "installer"))
import axiom_install as ai  # noqa: E402


class OverlaySources(unittest.TestCase):
    def test_every_overlay_source_is_in_the_build(self):
        airootfs = os.path.join(REPO, "iso/phase3/airootfs")
        build = open(os.path.join(REPO, "scripts/build-phase3-iso.sh")).read()
        missing = []
        for p in ai.OVERLAY:
            shipped = os.path.exists(os.path.join(airootfs, p.lstrip("/")))
            generated = p in build
            if not (shipped or generated):
                missing.append(p)
        self.assertEqual(missing, [], "overlay sources missing from the ISO build")


if __name__ == "__main__":
    unittest.main()
