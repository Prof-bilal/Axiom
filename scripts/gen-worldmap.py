#!/usr/bin/env python3
"""Generate apps/liveinstaller/worldmap.js: country outlines for the installer's time zone map.

    python3 scripts/gen-worldmap.py ne_50m_admin_0_countries.geojson [/usr/share/zoneinfo/zone.tab]

Input is Natural Earth 50m admin-0 countries (public domain, https://www.naturalearthdata.com/). It is read
once and is not kept in the repository; only the simplified outlines are. Each border is simplified
(Douglas-Peucker, TOLERANCE degrees) and stored as integers in tenths of a degree, equirectangular:
x = longitude * 10, y = latitude * 10. Countries are keyed by ISO_A2_EH, because ISO_A2 is -99 for France
and Norway. With a zone.tab path it also reports how many tzdata cities fall inside their own country.
"""
import json
import math
import sys

TOLERANCE = 0.12      # degrees; about 13 km at the equator
MIN_RING_AREA = 0.15  # square degrees; smaller islands are dropped unless they are a country's only land
LAT_MIN = -60.0       # Antarctica is not drawn
Q = 10                # stored units per degree


def simplify(pts, tol):
    """Douglas-Peucker on an open polyline, iterative so long coastlines cannot overflow the stack."""
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]
        bx, by = pts[b]
        dx, dy = bx - ax, by - ay
        norm = math.hypot(dx, dy)
        far, fi = 0.0, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            d = math.hypot(px - ax, py - ay) if norm == 0 else abs(dy * (px - ax) - dx * (py - ay)) / norm
            if d > far:
                far, fi = d, i
        if far > tol and fi >= 0:
            keep[fi] = True
            stack += [(a, fi), (fi, b)]
    return [p for p, k in zip(pts, keep) if k]


def area(ring):
    return abs(sum(ring[i][0] * ring[(i + 1) % len(ring)][1] - ring[(i + 1) % len(ring)][0] * ring[i][1]
                   for i in range(len(ring)))) / 2


def polygons(geom):
    if geom["type"] == "Polygon":
        yield geom["coordinates"]
    elif geom["type"] == "MultiPolygon":
        yield from geom["coordinates"]


def inside(x, y, ring):
    c = False
    j = len(ring) - 1
    for i in range(len(ring)):
        xi, yi = ring[i]
        xj, yj = ring[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            c = not c
        j = i
    return c


def edge_distance(x, y, ring):
    best = 1e9
    for i in range(len(ring)):
        ax, ay = ring[i]
        bx, by = ring[(i + 1) % len(ring)]
        dx, dy = bx - ax, by - ay
        t = 0 if dx == dy == 0 else max(0, min(1, ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy)))
        best = min(best, math.hypot(x - (ax + t * dx), y - (ay + t * dy)))
    return best


def coords(s):
    def dms(t, n):
        sign = -1 if t[0] == "-" else 1
        d = t[1:]
        sec = int(d[n + 2:n + 4]) if len(d) > n + 2 else 0
        return sign * (int(d[:n]) + int(d[n:n + 2]) / 60 + sec / 3600)
    i = max(s.rfind("+"), s.rfind("-"))
    return dms(s[:i], 2), dms(s[i:], 3)


def main(path, zone_tab=None):
    shapes = {}
    for f in json.load(open(path))["features"]:
        p = f["properties"]
        cc = p.get("ISO_A2_EH") or p.get("ISO_A2")
        if not cc or cc == "-99":
            continue
        rings = []
        for poly in polygons(f["geometry"]):
            ring = poly[0]
            if min(y for _, y in ring) < LAT_MIN and max(y for _, y in ring) < LAT_MIN + 5:
                continue
            rings.append(ring)
        if not rings:
            continue
        rings.sort(key=area, reverse=True)
        out = []
        for ring in rings:
            if out and area(ring) < MIN_RING_AREA:
                continue
            s = simplify(ring[:-1], TOLERANCE)
            if len(s) >= 3:
                out.append([(round(x * Q), round(y * Q)) for x, y in s])
        shapes.setdefault(cc, []).extend(out)
    body = ",\n".join(
        f'    ["{cc}", [' + ", ".join("[" + ",".join(f"{x},{y}" for x, y in r) + "]" for r in rs) + "]]"
        for cc, rs in sorted(shapes.items()))
    js = (".pragma library\n\n"
          "// Generated by scripts/gen-worldmap.py from Natural Earth 50m countries (public domain). Do not edit.\n"
          f"// Equirectangular outlines in tenths of a degree: x = longitude * {Q}, y = latitude * {Q}.\n"
          "// Each entry is [ISO_A2_EH, [ring, ring, ...]] and a ring is a flat [x, y, x, y, ...] list.\n\n"
          f"var Q = {Q}\nvar LAT_TOP = 84\nvar LAT_BOTTOM = {int(LAT_MIN)}\n"
          "var SHAPES = [\n" + body + "\n]\n")
    open("apps/liveinstaller/worldmap.js", "w").write(js)
    pts = sum(len(r) // 1 for rs in shapes.values() for r in rs)
    print(f"{len(shapes)} countries, {pts} points, {len(js) // 1024} KB")
    if zone_tab:
        ok = bad = 0
        misses = []
        real = {}
        for f in json.load(open(path))["features"]:
            cc = f["properties"].get("ISO_A2_EH")
            real.setdefault(cc, []).extend(polygons(f["geometry"]))
        for line in open(zone_tab):
            if line.startswith("#") or not line.strip():
                continue
            cc, c, zone = line.split("\t")[:3]
            lat, lon = coords(c)
            polys = [[(x / Q, y / Q) for x, y in r] for r in shapes.get(cc, [])]
            hit = any(inside(lon, lat, r) for r in polys)
            near = min((edge_distance(lon, lat, r) for r in polys), default=99)
            if hit or near <= 0.5:
                ok += 1
            else:
                bad += 1
                misses.append((zone, cc, round(near, 2)))
        print(f"zone.tab: {ok} cities in or within 0.5 deg of their own country, {bad} not")
        for m in misses[:40]:
            print("  miss", m)


if __name__ == "__main__":
    if not 2 <= len(sys.argv) <= 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])
