#!/usr/bin/env python3
"""Generate the labwc window themes (dark + light) from branding/theme/axiom/colors.toml.

Run after editing the palette. `--check` fails if the committed themerc files
are out of date (wired into validate-repo.py)."""
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
THEMES = ROOT / "iso/phase3/airootfs/usr/local/share/themes"
pal = tomllib.loads((ROOT / "branding/theme/axiom/colors.toml").read_text())
wc = pal["window_controls"]


def modes():
    b, c, li = pal["base"], pal["cyan"], pal["light"]
    dark = dict(bg=b["surface"], bg2="#0a0f12", border=b["border"], text=b["text_primary"],
                text2=b["text_secondary"], dim=b["text_disabled"], accent=c["primary"],
                accent_bd="#1d8f8d", sel="#123e40", hover="#ffffff18", glow="#22d3ee38", shadow="#00000050")
    light = dict(bg=li["surface"], bg2=li["surface_elevated"], border=li["border"], text=li["text_primary"],
                 text2=li["text_secondary"], dim="#8a9da1", accent=li["cyan"],
                 accent_bd=li["cyan"], sel="#cfeaf0", hover="#00000012", glow="#0a8fa630", shadow="#00000030")
    return {"Axiom": dark, "Axiom-Light": light}


TPL = """# GENERATED by scripts/gen-labwc-theme.py from branding/theme/axiom/colors.toml. Do not edit.
# Rules: docs/DESKTOP_DESIGN.md. Controls: close coral, minimize teal, maximize amber.

border.width: 1
window.titlebar.padding.width: 8
window.titlebar.padding.height: 4

window.active.border.color: {accent_bd}
window.inactive.border.color: {border}

window.active.title.bg.color: {bg}
window.inactive.title.bg.color: {bg2}
window.*.title.bg: Solid

window.active.label.text.color: {text}
window.inactive.label.text.color: {text2}
window.label.text.justify: left

window.button.width: 30
window.button.height: 26
window.button.spacing: 2
window.button.hover.bg.color: {hover}
window.button.hover.bg.corner-radius: 13

window.active.button.unpressed.image.color: {text2}
window.inactive.button.unpressed.image.color: {dim}
window.active.button.close.unpressed.image.color: {close}
window.inactive.button.close.unpressed.image.color: {close}88
window.active.button.iconify.unpressed.image.color: {minimize}
window.inactive.button.iconify.unpressed.image.color: {minimize}88
window.active.button.max.unpressed.image.color: {maximize}
window.inactive.button.max.unpressed.image.color: {maximize}88

window.active.shadow.size: 28
window.inactive.shadow.size: 18
window.active.shadow.color: {glow}
window.inactive.shadow.color: {shadow}

menu.overlap.x: 0
menu.overlap.y: 0
menu.width.min: 160
menu.width.max: 280
menu.border.width: 1
menu.border.color: {border}
menu.items.bg.color: {bg}
menu.items.text.color: {text}
menu.items.active.bg.color: {sel}
menu.items.active.text.color: {text}
menu.items.padding.x: 10
menu.items.padding.y: 6
menu.separator.width: 1
menu.separator.padding.width: 8
menu.separator.padding.height: 4
menu.separator.color: {border}
menu.title.bg.color: {bg}
menu.title.text.color: {text2}
menu.title.text.justify: Left

osd.bg.color: {bg}
osd.border.color: {border}
osd.border.width: 1
osd.label.text.color: {text}
osd.window-switcher.style-classic.width: 50%
osd.window-switcher.style-classic.item.active.border.color: {accent}
osd.window-switcher.style-classic.item.active.bg.color: {sel}
osd.window-switcher.preview.border.color: {accent}

snapping.overlay.region.border.color: {accent}
snapping.overlay.edge.border.color: {accent}
"""


def render():
    return {THEMES / name / "labwc/themerc": TPL.format(**m, **wc) for name, m in modes().items()}


if __name__ == "__main__":
    stale = []
    for path, text in render().items():
        if "--check" in sys.argv:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        sys.exit("stale (run scripts/gen-labwc-theme.py): " + ", ".join(stale))
