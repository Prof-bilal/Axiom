#!/usr/bin/env python3
"""Generate tui/penguin_art.py (pixel art for the console UI) from shell/assets/axiom-penguin.png.

    python3 scripts/gen-penguin-art.py

Classes per pixel: '.' empty, 'b' body, 'w' belly/face, 'o' beak/feet. The console renders two pixels
per cell with half blocks, so heights must be even. Needs Pillow (dev-time only, not on the ISO).
"""
import colorsys
import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "shell/assets/axiom-penguin.png")
SIZES = {"LARGE": (46, 46), "MEDIUM": (32, 32), "SMALL": (20, 20)}


def classify(r, g, b, a):
    if a < 110:
        return "."
    h, s, v = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
    if s > 0.45 and v > 0.45 and 0.04 < h < 0.15:
        return "o"
    if s < 0.28 and v > 0.62:
        return "w"
    return "b"


def build(img, w, h):
    bbox = img.getchannel("A").point(lambda x: 255 if x > 40 else 0).getbbox()
    sq = img.crop(bbox)
    side = max(sq.size)
    canvas = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    canvas.paste(sq, ((side - sq.width) // 2, side - sq.height))
    small = canvas.resize((w, h), Image.LANCZOS)
    return ["".join(classify(*small.getpixel((x, y))) for x in range(w)) for y in range(h)]


def main():
    img = Image.open(SRC).convert("RGBA")
    out = ['"""Pixel art for the console UI. Generated by scripts/gen-penguin-art.py; do not edit by hand."""', ""]
    for name, (w, h) in SIZES.items():
        rows = build(img, w, h)
        out.append(f"{name} = [")
        out += [f'    "{r}",' for r in rows]
        out += ["]", ""]
    path = os.path.join(ROOT, "tui/penguin_art.py")
    open(path, "w").write("\n".join(out))
    print("wrote", path)
    for r in build(img, *SIZES["LARGE"]):
        print(r.replace(".", " "))


main()
