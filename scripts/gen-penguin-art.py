#!/usr/bin/env python3
"""Generate tui/penguin_art.py: the Axiom penguin face in a round teal border, as console pixel art.

    python3 scripts/gen-penguin-art.py

The face is drawn from the eye and beak positions of shell/assets/axiom-penguin.png (reference pixel
coordinates), in the reference colours: teal ring, near-black disc, white eyes, dark pupils, orange beak.
Each target pixel takes the majority colour of its block. Classes: '.' empty or pupil, 'b' teal ring,
'k' dark disc, 'w' white eyes, 'o' beak. The console renders two pixels per cell with half blocks, so
heights must be even. Needs Pillow (dev-time only, not on the ISO).
"""
import os
from collections import Counter
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SIZES = {"LARGE": 40, "MEDIUM": 28, "SMALL": 16}  # square grids; heights are even
SUPER = 8  # draw at 8x, then take the majority colour of each target pixel
TEAL, WHITE, ORANGE, INK = (32, 214, 210), (255, 255, 255), (255, 148, 24), (0, 0, 0)
DARK = (30, 38, 42)  # the reference body is near-black with a teal glow
CLASS = {TEAL: "b", WHITE: "w", ORANGE: "o", INK: ".", DARK: "k"}
# The emblem's square in reference-image pixels: centred on the face, with room for the ring.
CX, CY, R_OUT, R_IN = 276, 178, 140, 126


def draw(n):
    """The face in an n x n grid: ring, disc, eyes, pupils and beak."""
    s = n * SUPER / (2 * R_OUT)
    img = Image.new("RGBA", (n * SUPER, n * SUPER), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)

    def P(x, y):
        return ((x - CX + R_OUT) * s, (y - CY + R_OUT) * s)

    def ell(x0, y0, x1, y1, colour):
        d.ellipse([*P(x0, y0), *P(x1, y1)], fill=colour + (255,))

    def poly(points, colour):
        d.polygon([P(x, y) for x, y in points], fill=colour + (255,))

    ell(CX - R_OUT, CY - R_OUT, CX + R_OUT, CY + R_OUT, TEAL)        # teal ring
    ell(CX - R_IN, CY - R_IN, CX + R_IN, CY + R_IN, DARK)            # dark disc
    ell(181, 105, 271, 195, WHITE)                                   # left eye
    ell(283, 105, 371, 190, WHITE)                                   # right eye
    ell(224, 136, 262, 174, INK)                                     # left pupil
    ell(296, 136, 334, 174, INK)                                     # right pupil
    poly([(210, 190), (345, 192), (278, 252)], ORANGE)               # beak
    return img


def sample(img, n):
    rows = []
    for y in range(n):
        row = []
        for x in range(n):
            block = img.crop((x * SUPER, y * SUPER, (x + 1) * SUPER, (y + 1) * SUPER))
            counts = Counter(p[:3] for p in block.getdata() if p[3] > 127)
            colour = counts.most_common(1)[0][0] if counts else None
            row.append(CLASS.get(colour, "."))
        rows.append("".join(row))
    return rows


def main():
    out = ['"""Pixel art for the console UI. Generated by scripts/gen-penguin-art.py; do not edit by hand."""', ""]
    for name, n in SIZES.items():
        out.append(f"{name} = [")
        out += [f'    "{r}",' for r in sample(draw(n), n)]
        out += ["]", ""]
    path = os.path.join(ROOT, "tui/penguin_art.py")
    with open(path, "w") as fh:
        fh.write("\n".join(out))
    print("wrote", path)


if __name__ == "__main__":
    main()
